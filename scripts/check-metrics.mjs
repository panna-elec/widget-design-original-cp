import assert from 'node:assert/strict';
import { reduceSample } from '../cyberdeck.widget/lib/metrics.js';
const make=(ticks,timestamp=100)=>({ticks,timestamp,memoryBytes:8,totalBytes:16});
assert.equal(reduceSample(null,make([1,2,3,4])).cpu,null);
assert.equal(reduceSample(make([10,20,30,0]),make([20,30,110,0],105)).cpu,20);
assert.equal(reduceSample(make([10,20,30,0]),make([10,20,30,0],105)).cpu,null);
assert.equal(reduceSample(make([10,20,30,0]),make([20,30,110,0],200)).cpu,null);
assert.equal(reduceSample(make([4294967290,20,30,0]),make([4,20,40,0],105)).cpu,50);
assert.throws(()=>reduceSample(null,make([NaN,1,2,3])));
assert.throws(()=>reduceSample(null,{...make([1,2,3,4]),totalBytes:0}));
console.log('PASS: 7 metric checks (delta, first sample, sleep gap, wrap, invalid inputs)');

const net=(time,network,uptime=time)=>({...make([time,time,time,0],time),uptime,network});
const port=(rxBytes,txBytes,id='en0:6')=>({id,rxBytes,txBytes});
const base=net(100,[port(10000,20000)]);
const rate=(before,after)=>reduceSample(before,after).networkRate;
assert.deepEqual(rate(base,net(105,[port(20240,25120)])),{rx:2048,tx:1024,status:'ok'});
assert.deepEqual(rate(base,net(105,[port(10000,20000)])),{rx:0,tx:0,status:'ok'});
assert.equal(rate(null,base).status,'waiting');
assert.equal(rate(base,net(105,[port(1,1)])).rx,null);
assert.equal(rate(base,net(105,[port(20240,25120,'en1:7')])).status,'waiting');
assert.equal(rate(base,net(130,[port(20240,25120)])).status,'waiting');
assert.equal(rate(base,net(105,[port(20240,25120)],101)).status,'waiting');
assert.equal(rate(base,net(105,[])).status,'no-interface');
assert.equal(rate(base,net(105,null)).status,'unavailable');
assert.equal(rate(base,net(105,[port(NaN,0)])).status,'unavailable');
assert.equal(rate(base,net(105,[port(0,0),port(0,0)])).status,'unavailable');
assert.equal(rate(base,net(100,[port(20240,25120)])).status,'waiting');
assert.equal(rate(base,net(105,[port(20240,25120),port(1,1,'en1:7')])).status,'waiting');
const both=net(100,[port(10000,20000),port(30000,40000,'en1:7')]);
assert.deepEqual(rate(both,net(105,[port(35120,45120,'en1:7'),port(20240,25120)])),{rx:3072,tx:2048,status:'ok'});
assert.equal(rate(net(100,[port(2**32-1024,100)]),net(105,[port(1024,200)])).rx,null);
console.log('PASS: 15 network checks (rates, idle, initial/reset/wrap, interface changes, sleep, clock, missing/invalid counters, aggregation)');
